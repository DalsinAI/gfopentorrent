#!/bin/sh
# GFOpenTorrent: PicoTorrent's database migrations as a C++ table, in place
# of the Windows resources Database::Migrate enumerates. Reads the
# DBMIGRATION lines of src/picotorrent/resources.rc, in their order, and
# writes gfot::db::migrations (compat/gfot_db.hpp) with each .sql file's text.
#   tools/stove/gen-migrations.sh PICOTORRENT_TREE OUT.cpp
# Copyright (c) 2026 AmiCradle Team. MIT licence.
set -eu
T=$1
OUT=$2
RC="$T/src/picotorrent/resources.rc"
[ -f "$RC" ] || { echo "gen-migrations: no $RC" >&2; exit 1; }
tmp="$OUT.tmp"
{
    echo "// generated by tools/stove/gen-migrations.sh from resources.rc"
    echo "#include \"gfot_db.hpp\""
    echo "const gfot::db::migration gfot::db::migrations[] = {"
} > "$tmp"
n=0
# NAME   DBMIGRATION "..\\..\\res\\dbmigrations\\NAME.sql"
tr -d '\r' < "$RC" | awk '$2 == "DBMIGRATION" { print $1 }' > "$tmp.names"
while read -r name; do
    sql="$T/res/dbmigrations/$name.sql"
    [ -f "$sql" ] || { echo "gen-migrations: no $sql" >&2; rm -f "$tmp" "$tmp.names"; exit 1; }
    if grep -q ')gfotsql"' "$sql"; then
        echo "gen-migrations: $sql holds the raw-string end" >&2; rm -f "$tmp" "$tmp.names"; exit 1
    fi
    printf '    { "%s", R"gfotsql(' "$name" >> "$tmp"
    tr -d '\r' < "$sql" >> "$tmp"
    printf ')gfotsql" },\n' >> "$tmp"
    n=$((n + 1))
done < "$tmp.names"
rm -f "$tmp.names"
[ "$n" -gt 0 ] || { echo "gen-migrations: no DBMIGRATION lines in $RC" >&2; rm -f "$tmp"; exit 1; }
{
    echo "};"
    echo "const std::size_t gfot::db::migration_count = $n;"
} >> "$tmp"
mv "$tmp" "$OUT"
echo "gen-migrations: $n migrations"
